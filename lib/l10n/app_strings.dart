const List<String> supportedLanguages = ['en', 'ru', 'fr', 'de', 'es'];

class L10n {
  const L10n(this.code);

  final String code;

  static bool isSupported(String? code) =>
      code != null && supportedLanguages.contains(code);

  String t(String key, [Map<String, String>? args]) {
    final dict = appStrings[code] ?? appStrings['en']!;
    var value = dict[key] ?? appStrings['en']![key] ?? key;
    args?.forEach((name, replacement) {
      value = value.replaceAll('{$name}', replacement);
    });
    return value;
  }
}
